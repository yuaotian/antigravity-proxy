  /**
   * 解析界面语言：pref 为插件设置（auto/zh-cn/en/ru），uiLang 为 IDE 显示语言（vscode.env.language）。
   * @param {string} [pref] @param {string} [uiLang]
   * @returns {"zh-cn" | "en" | "ru"}
   */
  function resolveLang(pref, uiLang) {
    const p = String(pref || "auto").toLowerCase();
    const src = p === "auto" ? String(uiLang || "en").toLowerCase() : p;
    if (src.startsWith("zh")) return "zh-cn";
    if (src.startsWith("ru")) return "ru";
    return "en";
  }

  /**
   * 生成翻译函数；缺失词条回退英文，再回退为 key 本身（便于发现漏译）。
   * @param {string} lang
   * @returns {(key: string, params?: Record<string, any>) => string}
   */
  function createT(lang) {
    const idx = Math.max(0, LANGS.indexOf(lang));
    return (key, params) => {
      const entry = M[key];
      let s = entry ? (entry[idx] || entry[1]) : key;
      if (params) s = s.replace(/\{(\w+)\}/g, (all, name) => (name in params ? String(params[name]) : all));
      return s;
    };
  }

  return { LANGS, HTML_LANG, MESSAGES: M, resolveLang, createT };
